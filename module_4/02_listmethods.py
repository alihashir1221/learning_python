variable = [1,45,2,98,4,7,4,1,5,6,89,99,785]

#sorts the list in ascending order
variable.sort()
print(variable)

#list.reverse() reverses the list from end to start
variable.reverse()
print(variable)

#list.append(add item in the list)
variable.append(784)
print(variable)

#list.insert(this is the index, this the item that needs to be added)
variable.insert(2,85)
print(variable)

#list.pop(delete the item at that index)
variable.pop(5)
print(variable)

#list.remove(removes the item from the list)
variable.remove(99)
print(variable)