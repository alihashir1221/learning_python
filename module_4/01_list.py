#LISTS AND TUPLES 
#IN Python, lists and tuples are both used to store collections of items. However, there are some key differences between the two.
#Lists are mutable, meaning you can change their content after creation.
list = ["ali", 7 , True, 3.14]
print(list)
print(list[0]) #accessing the first element of the list
print(list[3]) #accessing the second element of the list
print(list[2]) #accessing the third element of the list

#Unlike strings lists are mutable, meaning you can change their content after creation. You can add, remove, or modify elements in a list.
list[0] = "Grapes" #changing the first element of the list
print(list)